#!/usr/bin/env python3
"""Generate HTML5 character references from Python's WHATWG entity table.

Reference: https://html.spec.whatwg.org/multipage/named-characters.html
The checked-in header makes ordinary OS builds independent of Python.
"""
from html.entities import html5
from pathlib import Path

output = ["/* Generated by tools/mkentities.py; HTML5 names include their semicolon.",
          " * Entries without one are the legacy forms permitted by the tokenizer. */",
          f"#define HTML_ENTITY_MAX_NAME {max(map(len, html5))}",
          "static const struct entity { const char *name; int cp, second; } entities[] = {"]
for name, value in sorted(html5.items()):
    points = [ord(c) for c in value]
    assert 1 <= len(points) <= 2
    output.append(f'    {{ "{name}", 0x{points[0]:X}, 0x{points[1] if len(points) > 1 else 0:X} }},')
output.append("};\n")
Path(__file__).resolve().parents[1].joinpath("user/desktop/html_entities.h").write_text("\n".join(output))
