#!/usr/bin/env python3
"""
Make the fluxOS logo's pictures from assets/fluxos-logo.png (the logo,
assets/fluxos-logo.svg, drawn at 2000 x 2000: a single black shape).

  lib/logo.c   the logo at 128 x 128 as C source, for the kernel's startup
               and panic screens and the desktop's shutdown screen, screen
               saver and Setup backdrop. Each of them draws it over a dark
               background, so it is the shape in white.
  rootfs/usr/share/icons/{breeze,oxygen}/NxN/fluxos.png
               the fluxOS icon (16, 24, 32 and 48 pixels), the shape in
               black as drawn, filling the square: its stem and bar are 3/8
               of it, whole pixels at these sizes, so they stay sharp. Where it sits on dark chrome (the Start button) the
               desktop draws it in the chrome's text color instead.

The output is checked in, so building fluxOS does not need this script,
Python or PIL.

usage: tools/mklogo.py   (run from the top of the source tree)
"""
from PIL import Image

SIZE = 128
ICON_SIZES = (16, 24, 32, 48)
ICON_SETS = ("breeze", "oxygen")

src = Image.open("assets/fluxos-logo.png").convert("RGBA")
alpha = src.getchannel("A")


def ink(mask, rgb):
    """The shape (mask's coverage) in one color."""
    im = Image.new("RGBA", mask.size, rgb + (0,))
    im.putalpha(mask)
    return im


# lib/logo.c: white, the whole square
mask = alpha.resize((SIZE, SIZE), Image.LANCZOS)
out = [
    "/*",
    " * The fluxOS logo, %d x %d, as 0xAARRGGBB pixels row by row (not" % (SIZE, SIZE),
    " * premultiplied): the shape in white, for dark backgrounds, from",
    " * assets/fluxos-logo.png (generated by tools/mklogo.py).",
    " */",
    "#include <flux/logo.h>",
    "",
    "const uint32_t fluxos_logo[FLUXOS_LOGO_SIZE * FLUXOS_LOGO_SIZE] = {",
]
vals = []
for y in range(SIZE):
    for x in range(SIZE):
        a = mask.getpixel((x, y))
        vals.append("0x%08X" % (a << 24 | (0xFFFFFF if a else 0)))
for i in range(0, len(vals), 8):
    out.append("    " + ", ".join(vals[i:i + 8]) + ",")
out.append("};")
with open("lib/logo.c", "w") as f:
    f.write("\n".join(out) + "\n")

# the icons: black, the whole square
for size in ICON_SIZES:
    icon = ink(alpha.resize((size, size), Image.LANCZOS), (0, 0, 0))
    for theme in ICON_SETS:
        icon.save("rootfs/usr/share/icons/%s/%dx%d/fluxos.png" % (theme, size, size), optimize=True)
