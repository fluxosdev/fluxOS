#!/usr/bin/env python3
"""
Generate lib/logo.c, the fluxOS logo as C source for the kernel's startup
screen and the desktop's shutdown screen: assets/fluxos-logo.png scaled to
128 x 128, as 0xAARRGGBB pixels (not premultiplied). The output is checked
in, so building fluxOS does not need this script, Python or PIL.

usage: tools/mklogo.py   (run from the top of the source tree)
"""
from PIL import Image

SIZE = 128

im = Image.open("assets/fluxos-logo.png").convert("RGBA").resize((SIZE, SIZE), Image.LANCZOS)
px = im.load()
out = [
    "/*",
    " * The fluxOS logo, %d x %d, as 0xAARRGGBB pixels row by row (not" % (SIZE, SIZE),
    " * premultiplied), from assets/fluxos-logo.png (generated by tools/mklogo.py).",
    " */",
    "#include <flux/logo.h>",
    "",
    "const uint32_t fluxos_logo[FLUXOS_LOGO_SIZE * FLUXOS_LOGO_SIZE] = {",
]
vals = []
for y in range(SIZE):
    for x in range(SIZE):
        r, g, b, a = px[x, y]
        if a == 0:
            r = g = b = 0
        vals.append("0x%08X" % (a << 24 | r << 16 | g << 8 | b))
for i in range(0, len(vals), 8):
    out.append("    " + ", ".join(vals[i:i + 8]) + ",")
out.append("};")
with open("lib/logo.c", "w") as f:
    f.write("\n".join(out) + "\n")
