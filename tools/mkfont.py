#!/usr/bin/env python3
"""
Generate fluxOS's bitmap fonts as C source. The output is checked in, so
building fluxOS does not need this script, Python or PIL.

  lib/font8x16.c           8x16 VGA terminal font, ASCII 32-126, from the
                           Linux console font Lat15-VGA16 (kbd package)
  user/desktop/font_sans.c proportional UI fonts (regular and bold, and a
                           larger bold one for the Start menu banner), ASCII
                           32-126, rasterised monochrome with hinting from
                           Liberation Sans (SIL Open Font License 1.1)

usage: tools/mkfont.py   (run from the top of the source tree)
"""
import gzip
import struct

from PIL import Image, ImageDraw, ImageFont

PSF = "/usr/share/consolefonts/Lat15-VGA16.psf.gz"
SANS = "/usr/share/fonts/truetype/liberation/LiberationSans-Regular.ttf"
SANS_BOLD = "/usr/share/fonts/truetype/liberation/LiberationSans-Bold.ttf"
SANS_PX = 12
BANNER_PX = 16
FIRST, LAST = 32, 126


def psf1_ascii(path):
    data = gzip.open(path).read()
    magic, mode, height = struct.unpack("<HBB", data[:4])
    assert magic == 0x0436, "not a PSF1 font"
    count = 512 if mode & 1 else 256
    glyphs = [data[4 + i * height:4 + (i + 1) * height] for i in range(count)]
    index = {}
    if mode & 2:                        # unicode table: u16 lists, 0xFFFF ends
        pos, g = 4 + count * height, 0
        while g < count and pos + 1 < len(data):
            (u,) = struct.unpack("<H", data[pos:pos + 2])
            pos += 2
            if u == 0xFFFF:
                g += 1
            elif u != 0xFFFE:
                index.setdefault(u, g)
    assert height == 16
    return [glyphs[index.get(c, c)] for c in range(FIRST, LAST + 1)]


def write_font8x16(path):
    rows = psf1_ascii(PSF)
    with open(path, "w") as f:
        f.write("/*\n * 8x16 VGA font, ASCII 32-126 (generated by tools/mkfont.py from the\n"
                " * Linux console font Lat15-VGA16). One byte per row, MSB is leftmost.\n */\n")
        f.write("#include <flux/font.h>\n\n")
        f.write("const uint8_t font8x16[FONT_GLYPHS][16] = {\n")
        for c, g in zip(range(FIRST, LAST + 1), rows):
            f.write("    { %s },  /* %r */\n" % (", ".join("0x%02x" % b for b in g), chr(c)))
        f.write("};\n")


def rasterise(ttf, px):
    font = ImageFont.truetype(ttf, px)
    ascent, descent = font.getmetrics()
    height = ascent + descent
    glyphs = []
    for c in range(FIRST, LAST + 1):
        ch = chr(c)
        advance = int(round(font.getlength(ch)))
        img = Image.new("1", (32, height), 0)
        d = ImageDraw.Draw(img)
        d.fontmode = "1"
        d.text((1, ascent), ch, font=font, fill=1, anchor="ls")
        px = img.load()
        cols = [x for x in range(32) for y in range(height) if px[x, y]]
        left = min(cols) if cols else 1
        right = max(cols) + 1 if cols else 1
        # Keep the ink, starting at the origin (column 1) or where the ink
        # starts if it overhangs to the left.
        x0 = min(left, 1)
        width = max(right - x0, 0)
        assert width <= 16, "glyph %r too wide" % ch
        bits = []
        for y in range(height):
            row = 0
            for x in range(width):
                if px[x0 + x, y]:
                    row |= 0x8000 >> x
            bits.append(row)
        glyphs.append((ch, advance, x0 - 1, width, bits))
    return ascent, height, glyphs


def write_sans(path):
    with open(path, "w") as f:
        f.write("/*\n * Proportional UI fonts, ASCII 32-126 (generated by tools/mkfont.py).\n"
                " * Rasterised at %dpx (the banner font at %dpx) from Liberation Sans, which\n"
                " * is licensed under the SIL Open Font License 1.1. One u16 per row, MSB\n"
                " * is leftmost.\n */\n" % (SANS_PX, BANNER_PX))
        f.write('#include "font.h"\n')
        for name, ttf, px in (("font_sans", SANS, SANS_PX), ("font_sans_bold", SANS_BOLD, SANS_PX),
                              ("font_banner", SANS_BOLD, BANNER_PX)):
            ascent, height, glyphs = rasterise(ttf, px)
            f.write("\nstatic const uint16_t %s_bits[][%d] = {\n" % (name, height))
            for ch, _, _, _, bits in glyphs:
                f.write("    { %s },  /* %r */\n" % (", ".join("0x%04x" % b for b in bits), ch))
            f.write("};\n\n")
            f.write("const struct pfont %s = {\n    .height = %d,\n    .ascent = %d,\n"
                    "    .glyphs = {\n" % (name, height, ascent))
            for i, (ch, adv, xoff, width, _) in enumerate(glyphs):
                f.write("        { %d, %d, %d, %s_bits[%d] },  /* %r */\n"
                        % (adv, xoff, width, name, i, ch))
            f.write("    },\n};\n")


if __name__ == "__main__":
    write_font8x16("lib/font8x16.c")
    write_sans("user/desktop/font_sans.c")
